export const truncateDecimalTo = (val, decimals = 4) => {
  if (val === null || val === undefined) return null;
  const s = String(val).trim();
  if (s === "") return null;
  const neg = s.startsWith("-") ? "-" : "";
  const t = neg ? s.slice(1) : s;
  if (!t.includes(".")) return `${neg}${t}.${"0".repeat(decimals)}`;
  const [intPart, fracPart] = t.split(".");
  const fracPad = (fracPart + "0".repeat(decimals)).slice(0, decimals);
  return `${neg}${intPart}.${fracPad}`;
};
